// LookupVendor resolves a MAC address to a vendor name using the embedded IEEE OUI table
// and flags locally-administered randomized MAC addresses (modern iOS/Android/Win11 privacy MACs).
func LookupVendor(mac string) (vendor string, isRandomized bool) {
	norm := config.NormalizeMAC(mac)
	if len(norm) < 8 {
		return "Fabricante desconocido", false
	}

	parts := strings.Split(norm, ":")
	if len(parts) < 3 {
		return "Fabricante desconocido", false
	}

	firstOctet, err := strconv.ParseUint(parts[0], 16, 8)
	if err == nil {
		// Bit 1 (0x02) = locally administered; Bit 0 (0x01) = multicast (must be 0 for unicast)
		if firstOctet&0x02 != 0 && firstOctet&0x01 == 0 {
			return "MAC Aleatoria (Privada)", true
		}
	}

	prefix := parts[0] + ":" + parts[1] + ":" + parts[2]
	if v, ok := ouiTable[prefix]; ok {
		return v, false
	}
	return "Fabricante desconocido", false
}
