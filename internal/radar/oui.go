//go:embed oui_extra.txt.gz
var extraOUIGzip []byte

func init() {
	if len(extraOUIGzip) == 0 {
		return
	}
	zr, err := gzip.NewReader(bytes.NewReader(extraOUIGzip))
	if err != nil {
		return
	}
	defer zr.Close()

	scanner := bufio.NewScanner(zr)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue
		}
		eq := strings.IndexByte(line, '=')
		if eq <= 0 {
			continue
		}
		prefix := strings.ToUpper(strings.TrimSpace(line[:eq]))
		vendor := strings.TrimSpace(line[eq+1:])
		if len(prefix) == 8 && vendor != "" {
			if _, exists := ouiTable[prefix]; !exists {
				ouiTable[prefix] = vendor
			}
		}
	}
}

